// Writes tauri/src-tauri/src/db/week_data.rs from the JSON collectWeekData
// returned: `node week-rs.js <week.json> <out.rs>`.
const fs = require("node:fs");
const [, , input, output] = process.argv;
const d = JSON.parse(fs.readFileSync(input, "utf8"));
const list = (items) => items.map((s) => `    "${s}",`).join("\n");
const days = (map) =>
  Object.entries(map)
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([k, v]) => `    ("${k}", ${v}),`)
    .join("\n");
const sorted = (items) => [...items].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
const out = `//! Generated by docs/tauri-port/units/T13/week-rs.js from the week data
//! Electron's ICU reports. Do not edit by hand.

/// \`firstDayOfWeek(undefined)\`.
pub const DEFAULT_DAY: u8 = ${d.defaultDay};

/// Regions whose week does not open on Monday, sorted.
pub const REGION_DAYS: &[(&str, u8)] = &[
${days(d.regionDays)}
];

/// Deprecated regions and the region \`Intl.getCanonicalLocales\` puts in
/// their place, sorted.
pub const REGION_ALIASES: &[(&str, &str)] = &[
${Object.entries(d.regionAliases)
  .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
  .map(([k, v]) => `    ("${k}", "${v}"),`)
  .join("\n")}
];

/// Deprecated languages and the tag \`Intl.getCanonicalLocales\` puts in
/// their place, sorted. Only aliases onto a language ICU has are kept: any
/// other resolves to the default locale either way.
pub const LANGUAGE_ALIASES: &[(&str, &str)] = &[
${Object.entries(d.languageAliases)
  .filter(([, to]) => d.bases.includes(to.split("-").filter((s) => !/^([A-Z]{2}|\d{3})$/.test(s)).join("-")))
  .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
  .map(([k, v]) => `    ("${k}", "${v}"),`)
  .join("\n")}
];

/// Language and language-script tags ICU has, sorted.
pub const BASES: &[&str] = &[
${list(sorted(d.bases))}
];

/// The tags in [\`BASES\`] whose week does not open on Monday, sorted.
pub const BASE_DAYS: &[(&str, u8)] = &[
${days(d.baseDays)}
];

/// Tags with a region that ICU has, sorted.
pub const WITH_REGION: &[&str] = &[
${list(sorted(d.withRegion))}
];

/// \`firstDayOfWeek(tag)\` for tags an OS reports, as Electron answered.
#[cfg(test)]
pub const PROBES: &[(&str, u8)] = &[
${days(d.probes)}
];
`;
fs.writeFileSync(output, out);
