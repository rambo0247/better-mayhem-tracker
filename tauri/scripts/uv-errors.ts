// Writes src-tauri/src/backup/uv_errors.rs: libuv's names and messages for the
// errors Node prints from fs calls, so the port's file errors read as
// Electron's do. Runs in Node on macOS, whose util.getSystemErrorMap() is the
// libuv table Electron ships (Electron 44 bundles Node 24.21.0 and libuv
// 1.52.1, the same libuv as Node 26.8.1).
//
//   node scripts/uv-errors.ts <libuv src/win/error.c> <windows-sys crate dir>
//
// error.c must be the one from the libuv tag this Node reports, at
// https://raw.githubusercontent.com/libuv/libuv/v<uv>/src/win/error.c. The
// windows-sys crate only supplies the numeric value of each Win32 constant.
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import util from "node:util";

const [errorC, windowsSys] = process.argv.slice(2);
if (!errorC || !windowsSys) {
  throw new Error("usage: node scripts/uv-errors.ts <error.c> <windows-sys crate dir>");
}
const versions: Record<string, string | undefined> = process.versions;
if (versions.bun !== undefined || process.platform !== "darwin") {
  throw new Error("run this in Node on macOS: the errno table is the Mac's");
}

const out = resolve(
  dirname(fileURLToPath(import.meta.url)),
  "../src-tauri/src/backup/uv_errors.rs",
);
const systemErrors = util.getSystemErrorMap();

// libuv's own codes, getaddrinfo's included, sit at -3000 and below. The rest
// are negated host errnos.
const macErrno = new Map<number, string>();
const messages = new Map<string, string>();
for (const [code, [name, message]] of systemErrors) {
  messages.set(name, message);
  if (code < 0 && code > -3000) macErrno.set(-code, name);
}

const source = readFileSync(errorC, "utf8");
const body = source.slice(source.indexOf("int uv_translate_sys_error("));
const cases = [
  ...body.slice(0, body.indexOf("default:")).matchAll(/case (\w+):\s*return UV_(\w+);/g),
];
if (cases.length === 0) throw new Error(`no cases in ${errorC}`);

const constants = new Map<string, number>();
for (const file of ["Foundation/mod.rs", "Networking/WinSock/mod.rs"]) {
  const text = readFileSync(join(windowsSys, "src/Windows/Win32", file), "utf8");
  for (const [, name, value] of text.matchAll(/^pub const (\w+): \w+ = (\d+)[iu]32;$/gm)) {
    constants.set(name!, Number(value));
  }
}

const win32 = new Map<number, string>();
for (const [, constant, name] of cases) {
  const value = constants.get(constant!);
  if (value === undefined) throw new Error(`windows-sys has no ${constant}`);
  if (!messages.has(name!)) throw new Error(`Node has no message for ${name}`);
  win32.set(value, name!);
}

const arms = (table: Map<number, string>) =>
  [...table].sort(([a], [b]) => a - b).map(([value, name]) => `        ${value} => "${name}",`);
const sha = createHash("sha256").update(source).digest("hex");

writeFileSync(
  out,
  `//! Generated by \`tauri/scripts/uv-errors.ts\` in Node ${process.version}, libuv
//! ${versions.uv}, from \`util.getSystemErrorMap()\` on macOS and libuv's
//! \`src/win/error.c\`, sha256
//! ${sha}. Do not edit.

/// libuv's name for a macOS errno.
#[cfg(target_os = "macos")]
pub fn uv_code(errno: i32) -> Option<&'static str> {
    Some(match errno {
${arms(macErrno).join("\n")}
        _ => return None,
    })
}

/// libuv's name for a Win32 error, as \`uv_translate_sys_error\` gives it.
#[cfg(windows)]
pub fn uv_code(error: i32) -> Option<&'static str> {
    Some(match error {
${arms(win32).join("\n")}
        _ => return None,
    })
}

#[cfg(not(any(target_os = "macos", windows)))]
pub fn uv_code(_errno: i32) -> Option<&'static str> {
    None
}

/// \`uv_strerror\` for a libuv name.
pub fn uv_message(code: &str) -> &'static str {
    match code {
${[...messages]
  .sort(([a], [b]) => (a < b ? -1 : 1))
  .map(([name, message]) => `        "${name}" => "${message}",`)
  .join("\n")}
        _ => "unknown error",
    }
}
`,
);
execFileSync("rustfmt", ["--edition", "2024", out], { stdio: "inherit" });
console.log(
  `${out}: ${macErrno.size} macOS errnos, ${win32.size} Win32 errors, ${messages.size} messages`,
);
