//! Writes `tauri/src/bindings.ts` from the Rust contract: every type the
//! commands and events carry, the channel map, `RendererEvents`, and one
//! typed wrapper per command in Electron's positional order.
//!
//! `cargo run --bin export_bindings --features export-bindings` writes it.
//! With `--check` it writes nothing and fails when the file is stale.

use std::fmt::Write as _;
use std::path::PathBuf;
use std::process::ExitCode;

use bmt_lib::commands::{self, CommandSpec, TypeCollector, TypeSpec};
use bmt_lib::events;
use ts_rs::Config;

fn ts_return(spec: &TypeSpec, cfg: &Config) -> String {
    if spec.unit {
        "void".into()
    } else {
        (spec.ts)(cfg)
    }
}

fn wrapper(command: &CommandSpec, cfg: &Config) -> String {
    let params: Vec<String> = command
        .args
        .iter()
        .map(|arg| {
            let key = arg.key();
            if arg.ty.optional {
                format!("{key}?: {}", (arg.ty.inner_ts)(cfg))
            } else {
                format!("{key}: {}", (arg.ty.ts)(cfg))
            }
        })
        .collect();
    let keys: Vec<String> = command.args.iter().map(|arg| arg.key()).collect();
    let ret = ts_return(&command.ret, cfg);
    // Tauri resolves a command that returns nothing with null, Electron with undefined
    let tail = if command.ret.unit {
        ".then(() => undefined)"
    } else {
        ""
    };
    format!(
        "  {method}: ({params}): Promise<{ret}> =>\n    call<{ret}>(\"{channel}\", {named}, [{positional}]){tail},\n",
        method = command.method,
        params = params.join(", "),
        channel = command.channel,
        named = if keys.is_empty() {
            "{}".to_string()
        } else {
            format!("{{ {} }}", keys.join(", "))
        },
        positional = keys.join(", "),
    )
}

// Set in code: ts-rs reads TS_RS_LARGE_INT only through Config::from_env, and
// without it every i64 prints as bigint
fn config() -> Config {
    Config::new().with_large_int("number")
}

fn render() -> String {
    let cfg = config();
    let registry = commands::registry();
    let events = events::event_specs();

    let mut collector = TypeCollector::new(config());
    for command in &registry {
        for arg in &command.args {
            (arg.ty.visit)(&mut collector);
        }
        (command.ret.visit)(&mut collector);
    }
    for event in &events {
        (event.payload.visit)(&mut collector);
    }

    let mut out = String::new();
    out.push_str(
        "// Generated by src-tauri/src/bin/export_bindings.rs from the Rust command contract.\n\
         // Do not edit. Regenerate with `cargo run --bin export_bindings --features export-bindings`.\n\n",
    );
    for decl in collector.decls.values() {
        writeln!(out, "export {decl}\n").expect("write to a string");
    }

    out.push_str("/** Every request method's Electron channel. */\nexport const CHANNELS = {\n");
    for command in &registry {
        writeln!(out, "  {}: \"{}\",", command.method, command.channel).expect("write to a string");
    }
    out.push_str("} as const;\n\n");

    out.push_str("/** What the main process pushes to the main window, and each payload. */\nexport interface RendererEvents {\n");
    for event in &events {
        writeln!(
            out,
            "  \"{}\": {};",
            event.name,
            ts_return(&event.payload, &cfg)
        )
        .expect("write to a string");
    }
    out.push_str("}\n\n");

    out.push_str(
        "/**\n * Sends one request: the channel, the arguments keyed as the Rust command names them, and the\n * same arguments in Electron's positional order.\n */\n\
         export type Transport = <T>(channel: string, args: Record<string, unknown>, positional: unknown[]) => Promise<T>;\n\n\
         export const createCommands = (call: Transport) => ({\n",
    );
    for command in &registry {
        out.push_str(&wrapper(command, &cfg));
    }
    out.push_str("});\n");
    out
}

fn main() -> ExitCode {
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../src/bindings.ts");
    let rendered = render();
    // api.ts types every integer as number; a bigint means the large-int
    // setting was lost and every i64 changed type
    if rendered.contains("bigint") {
        eprintln!("the bindings type an integer as bigint; api.ts has number");
        return ExitCode::FAILURE;
    }
    if std::env::args().any(|a| a == "--check") {
        let current = std::fs::read_to_string(&path).unwrap_or_default();
        if current == rendered {
            println!("{} is fresh", path.display());
            return ExitCode::SUCCESS;
        }
        eprintln!(
            "{} is stale. Run `cargo run --bin export_bindings --features export-bindings`.",
            path.display()
        );
        return ExitCode::FAILURE;
    }
    std::fs::write(&path, &rendered).expect("write bindings.ts");
    println!("wrote {}", path.display());
    ExitCode::SUCCESS
}
